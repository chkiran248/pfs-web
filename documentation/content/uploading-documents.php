<p>PrimoAI can read a statement you upload and turn it into portfolio entries automatically, instead of you entering each holding by hand.</p>

<h2>How it works</h2>
<div class="doc-steps">
  <div class="doc-step">
    <h3><span class="doc-step-num">1</span> Upload</h3>
    <p>Open PrimoAI (or the "Auto-Import" card on the Documents page) and drop in your file. If it's a password-protected PDF, enter the password up front — see <a href="documentation.php?page=cas-nsdl-statement">Get Your CAS / NSDL Statement</a> for where to find it.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">2</span> PrimoAI reads it</h3>
    <p>PrimoAI detects the document type — CAS, NSDL/CDSL, a broker statement (Zerodha, Groww, etc.), or an FD certificate — and extracts the relevant details: fund/stock names, folio numbers or ISINs, units, and values.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">3</span> Review the extracted holdings</h3>
    <p>You'll see a summary of everything PrimoAI found before anything is saved. Check it over — this is your chance to catch anything that looks off.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">4</span> Confirm to add to your portfolio</h3>
    <p>Confirm, and the holdings are added to your portfolio immediately — visible on your <a href="documentation.php?page=portfolio-tracking">Portfolio</a> page from that point on.</p>
  </div>
</div>

<h2>If a statement is password protected</h2>
<p>Enter the password in the field provided before uploading. Most CAS/NSDL/CDSL statements use your PAN in capitals — full details in <a href="documentation.php?page=cas-nsdl-statement">Get Your CAS / NSDL Statement</a>.</p>

<div class="doc-callout doc-callout--warn">
  <i class="bi bi-exclamation-triangle doc-callout-icon"></i>
  <p>If extraction fails or the password isn't accepted, you can still add holdings manually from the <a href="documentation.php?page=portfolio-tracking">Portfolio</a> page — or reach out via "Chat with Advisor" and we'll sort it out with you.</p>
</div>
