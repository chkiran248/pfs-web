<p>Goals connect your investments to what you're actually saving for — retirement, a home, your child's education, or anything else with a target amount and a timeline.</p>

<h2>Setting up a goal</h2>
<div class="doc-steps">
  <div class="doc-step">
    <h3><span class="doc-step-num">1</span> Define the goal</h3>
    <p>Give it a name, a target amount, and a target date.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">2</span> Link your investments</h3>
    <p>Point specific holdings or SIPs at the goal so its progress reflects real money, not just a plan.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">3</span> Track progress</h3>
    <p>Your Goals page shows how close you are, and whether your current investment pace will get you there on time.</p>
  </div>
</div>

