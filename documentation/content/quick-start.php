<p>Once you're logged in, here's a quick tour of the portal so you know where everything lives.</p>

<h2>Your sidebar, at a glance</h2>
<ul>
  <li><strong>PrimoAI</strong> — chat with your AI assistant, or upload a document to scan.</li>
  <li><strong>Overview</strong> — your dashboard, profile, and current plan.</li>
  <li><strong>My Finances</strong> — portfolio, goals, FD tracker, and rebalancer.</li>
  <li><strong>Tools</strong> — SIP, tax, NPS, and other calculators.</li>
  <li><strong>Advisory</strong> — mutual fund and stock research, sector tracking, model portfolios, market insights.</li>
  <li><strong>Watchlists</strong> — funds and stocks you're keeping an eye on.</li>
  <li><strong>Documents</strong> — everything you've uploaded or that's been shared with you.</li>
</ul>

<h2>Your first three steps</h2>
<div class="doc-steps">
  <div class="doc-step">
    <h3><span class="doc-step-num">1</span> Import your existing investments</h3>
    <p>If you already invest elsewhere, get your <a href="documentation.php?page=cas-nsdl-statement">CAS or NSDL/CDSL statement</a> and upload it — PrimoAI will read it and pre-fill your portfolio automatically.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">2</span> Set a financial goal</h3>
    <p>Head to <a href="documentation.php?page=goals">Goals</a> and define what you're investing for — retirement, a home, your child's education — so your portfolio has a target to track against.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">3</span> Ask PrimoAI a question</h3>
    <p>Try something like "How is my portfolio doing?" or "Am I on track for retirement?" — PrimoAI already has your context once your portfolio is imported.</p>
  </div>
</div>

<p>From there, explore the calculators and advisory sections whenever a specific question comes up — you don't need to use everything on day one.</p>
