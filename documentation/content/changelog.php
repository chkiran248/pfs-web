<p>A running record of what's new on the Prime Financials platform — in plain language, for clients rather than developers.</p>

<h2>Version 1.0 — August 2026</h2>

<h3>New</h3>
<ul>
  <li>This Documentation Center — step-by-step guides for every part of the platform, including how to get your CAS or NSDL/CDSL statement.</li>
  <li>PrimoAI can now scan a CAS, NSDL/CDSL, or broker statement you upload and automatically add the holdings to your portfolio.</li>
  <li>AI-assisted rebalancing suggestions for your mutual fund and equity holdings.</li>
  <li>Sign up and log in with Google, in addition to email and password.</li>
  <li>A new Cashfree-powered checkout for upgrading to a paid plan.</li>
  <li>A new default look — Comfortable Dark theme — with light mode still available from the toggle in the top navigation.</li>
</ul>

<h3>Improved</h3>
<ul>
  <li>Added extra security checks to sign-up and login to keep automated/bot accounts out.</li>
  <li>More accurate fund NAV and stock price data across the platform.</li>
  <li>Better contrast and logo visibility in light mode.</li>
</ul>

<h3>Fixed</h3>
<ul>
  <li>Various navigation, display, and access issues across advisory and account pages.</li>
</ul>

