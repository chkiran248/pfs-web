<p><strong>PrimoAI</strong> is your AI investment assistant, built into the portal — it understands your actual portfolio and goals, not just general financial advice.</p>

<h2>What PrimoAI can do</h2>
<ul>
  <li><strong>Answer questions about your portfolio</strong> — asset allocation, performance, biggest holdings, and more.</li>
  <li><strong>Scan and import documents</strong> — read a CAS, NSDL/CDSL statement, or broker PDF and extract your holdings automatically. See <a href="documentation.php?page=uploading-documents">Uploading Documents with PrimoAI</a>.</li>
  <li><strong>Suggest rebalancing</strong> — analyze your mutual fund and equity holdings and propose adjustments. See <a href="documentation.php?page=rebalancing">Rebalancing</a>.</li>
  <li><strong>Remember context across a conversation</strong> — so you don't have to re-explain your situation every time you ask something new.</li>
</ul>

