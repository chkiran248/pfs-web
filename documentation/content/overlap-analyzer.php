<p>It's common to end up holding several mutual funds that all own the same underlying stocks — which means you're carrying more concentrated risk than your fund count suggests. The Overlap Analyzer checks for exactly that.</p>

<h2>How it works</h2>
<p>The analyzer compares the stock-level holdings across your mutual funds and highlights where they overlap significantly — for example, if three of your five funds all have a large position in the same handful of large-cap stocks.</p>

<div class="doc-callout">
  <i class="bi bi-info-circle doc-callout-icon"></i>
  <p>High overlap isn't automatically bad, but it often means you're not getting the diversification you think you are by holding multiple funds. Worth a look especially before adding a new fund to your portfolio.</p>
</div>

