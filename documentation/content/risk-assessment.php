<p>Before recommending an asset allocation, it helps to know how much risk you're actually comfortable taking — not just how much you think you should take. The Risk Assessment quiz measures that.</p>

<h2>How it works</h2>
<p>Answer a short series of questions about your investment horizon, reaction to market drops, and financial goals. Based on your answers, you'll get a risk profile — from conservative to aggressive — that can guide how your mutual fund and equity allocation is structured.</p>

<div class="doc-callout">
  <i class="bi bi-lightbulb doc-callout-icon"></i>
  <p>Retaking the quiz periodically is a good idea — your risk tolerance can shift as your life circumstances change.</p>
</div>

