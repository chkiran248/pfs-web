<h2>Getting your NSDL / CDSL demat statement</h2>
<ul>
  <li><strong>NSDL</strong> — visit <strong>cas.nsdl.com</strong> and request your statement, or ask your broker/Depository Participant (DP) to email it to you.</li>
  <li><strong>CDSL</strong> — visit <strong>web.cdslindia.com</strong>, use the "easi/easiest" facility, and request your e-CAS.</li>
</ul>
<p>Not sure which depository holds your demat account? Check your broker's app or contract note — it's stated there, or your broker's support team can confirm it.</p>

<h2>Opening the password-protected PDF</h2>
<p>CAS and NSDL/CDSL statements are almost always delivered as password-protected PDFs. The password is typically your <strong>PAN number in capital letters</strong> (e.g. <code>ABCDE1234F</code>). If that doesn't work, check the email that delivered the statement — it usually states the exact password format used (some RTAs also require your date of birth).</p>

