<p>A <strong>CAS</strong> (Consolidated Account Statement) or an <strong>NSDL/CDSL demat statement</strong> is the fastest way to get your existing investments into Prime Financials — upload one PDF and PrimoAI extracts every holding automatically instead of you typing each one in by hand.</p>

<h2>CAS vs. NSDL/CDSL — what's the difference?</h2>
<ul>
  <li><strong>CAS (Consolidated Account Statement)</strong> — issued by the two mutual fund Registrars & Transfer Agents in India, <strong>CAMS</strong> and <strong>KFintech</strong> (formerly Karvy). It lists every mutual fund folio registered against your PAN, across all AMCs, in one document.</li>
  <li><strong>NSDL / CDSL demat statement</strong> — issued by India's two depositories. It lists equities (and mutual funds held in demat form) sitting in your demat account with your broker.</li>
</ul>
<p>If you only invest in mutual funds directly (not through a demat account), the CAS alone is usually enough. If you also hold stocks, or your mutual funds are held in demat form, get the NSDL/CDSL statement too.</p>

