<h2>Troubleshooting</h2>
<ul>
  <li><strong>Didn't receive the email?</strong> Check your spam folder, and confirm the email address you used matches the one registered with the RTA/depository — it won't arrive at a different address.</li>
  <li><strong>Wrong password?</strong> Double-check you're using your PAN in capital letters with no spaces. If it still fails, the delivery email will usually specify the exact format.</li>
  <li><strong>Extraction failed or looks wrong?</strong> Contact your advisor via WhatsApp using the "Chat with Advisor" button — we'll help you get it imported correctly.</li>
</ul>
