<p>If something goes wrong — a transaction issue, a service concern, or anything else — here's how to raise it.</p>

<h2>Step 1: Contact your advisor directly</h2>
<p>Most issues are resolved fastest this way. Reach out via the "Chat with Advisor" button in your portal, or email <strong>support@primefin.in</strong> / call <strong>+91 99800 01338</strong>. We aim to acknowledge every complaint promptly and resolve it as quickly as possible.</p>

<h2>Step 2: Escalate if unresolved</h2>
<p>If your concern isn't resolved to your satisfaction, as an AMFI-registered mutual fund distributor we're bound by industry grievance redressal norms — you can escalate to AMFI or, for capital markets matters, to SEBI directly through the <strong>SEBI SCORES</strong> portal (scores.sebi.gov.in).</p>

