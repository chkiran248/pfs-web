<p>Two tools help you plan around taxes: the Tax Calculator for a quick estimate, and the Tax Modeler for a deeper look at how different investments affect your liability.</p>

<h2>Tax Calculator</h2>
<p>Enter your income details to estimate your tax liability under the old and new tax regimes, so you can see which works out better for your situation.</p>

<h2>Tax Modeler</h2>
<p>Goes further than a single estimate — model how tax-saving investments (like ELSS funds, NPS contributions, or insurance premiums) shift your final tax outcome, so you can plan your tax-saving investments deliberately rather than at the last minute in March.</p>

