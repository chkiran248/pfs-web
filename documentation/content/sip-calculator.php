<p>The SIP Calculator projects how a monthly Systematic Investment Plan grows over time, based on your contribution amount, duration, and an assumed rate of return.</p>

<h2>What to enter</h2>
<ul>
  <li><strong>Monthly investment amount</strong></li>
  <li><strong>Investment duration</strong> (in years)</li>
  <li><strong>Expected annual return</strong> — a reasonable estimate based on the type of fund you're considering</li>
</ul>

<p>The calculator returns your total invested amount, projected value at the end of the period, and the wealth gained from compounding.</p>

