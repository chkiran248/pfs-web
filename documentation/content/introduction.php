<h2>Who this is for</h2>
<p>Prime Financials is built for Indian investors who want institutional-quality advice without giving up visibility into their own money. Whether you're just starting out or already invested across multiple funds, brokers, and RTAs, the platform brings everything into one place.</p>

<h2>What you can do here</h2>
<ul>
  <li><strong>Import your portfolio</strong> — upload a CAS or NSDL/CDSL statement and let PrimoAI extract your holdings automatically.</li>
  <li><strong>Track everything in one view</strong> — mutual funds, stocks, FDs, and insurance, alongside your financial goals.</li>
  <li><strong>Plan with calculators</strong> — SIP, tax, NPS, insurance adequacy, cashflow, and risk assessment tools.</li>
  <li><strong>Research before you invest</strong> — curated mutual fund and stock research, sector tracking, and model portfolios.</li>
  <li><strong>Ask PrimoAI</strong> — a conversational assistant that understands your actual portfolio and goals.</li>
</ul>

