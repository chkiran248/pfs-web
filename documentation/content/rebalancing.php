<p>Over time, your portfolio drifts from its original allocation — some investments grow faster than others. The Rebalancer helps you see that drift and decide what to do about it.</p>

<h2>How it works</h2>
<p>The Rebalancer looks at your current mutual fund and equity holdings and, using PrimoAI, suggests adjustments to bring your allocation back toward your target — for example, trimming an overweight sector or topping up an underweight asset class.</p>

<h2>Mutual funds vs. equities</h2>
<ul>
  <li><strong>Mutual fund rebalancing</strong> — suggestions based on fund category, allocation drift, and overlap with other funds you hold.</li>
  <li><strong>Equity rebalancing</strong> — suggestions based on your stock holdings' sector and concentration.</li>
</ul>

<div class="doc-callout">
  <i class="bi bi-info-circle doc-callout-icon"></i>
  <p>Rebalancing suggestions are a starting point for a conversation, not an automatic instruction — nothing is bought or sold on your behalf. Talk to your advisor before acting on a suggestion.</p>
</div>

