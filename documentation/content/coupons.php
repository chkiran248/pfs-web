<p>If your advisor has given you a coupon code, you can redeem it to unlock a paid plan without paying directly.</p>

<h2>How to redeem</h2>
<div class="doc-steps">
  <div class="doc-step">
    <h3><span class="doc-step-num">1</span> Go to Plans &amp; Pricing</h3>
    <p>Find the coupon entry field on the pricing page in your portal.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">2</span> Enter your code</h3>
    <p>Codes aren't case-sensitive.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">3</span> Done</h3>
    <p>Once accepted, your account is upgraded to the plan tied to that code — typically for a full year.</p>
  </div>
</div>

<div class="doc-callout doc-callout--warn">
  <i class="bi bi-exclamation-triangle doc-callout-icon"></i>
  <p>Each coupon code can only be redeemed once per account. If a code shows as invalid or already used, double-check for typos, or reach out to your advisor for a fresh one.</p>
</div>
