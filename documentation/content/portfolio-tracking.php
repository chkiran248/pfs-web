<p>Your Portfolio page is where every investment you hold — mutual funds, stocks, and fixed deposits — lives in one consolidated view.</p>

<h2>Getting your holdings in</h2>
<ul>
  <li><strong>Automatic import</strong> — upload your <a href="documentation.php?page=cas-nsdl-statement">CAS or NSDL/CDSL statement</a> and let PrimoAI extract everything at once.</li>
  <li><strong>Manual entry</strong> — add a holding directly on the Portfolio page if you'd rather enter it yourself, or if you're adding just one or two investments.</li>
</ul>

<h2>What you'll see</h2>
<p>For each holding: current value, units/quantity, and how it's performed. Mutual funds are valued using daily NAV data; stocks use live market prices. Together, this gives you a real-time read on your total net worth across investments.</p>

