<p>Fixed Deposits don't show up in a CAS or demat statement, so the FD Tracker gives them a dedicated home alongside your market investments.</p>

<h2>What you can track</h2>
<ul>
  <li>Principal amount and interest rate</li>
  <li>Start date and maturity date</li>
  <li>Which bank or issuer holds it</li>
</ul>

<p>Add each FD manually as you open it, and the tracker keeps a running view of your maturity schedule — useful for spotting when a ladder of FDs is about to come due, or for including FD value in your total net worth alongside mutual funds and stocks on your <a href="documentation.php?page=portfolio-tracking">Portfolio</a> page.</p>
