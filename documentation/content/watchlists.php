<p>Watchlists let you track mutual funds or stocks you're interested in — without needing to hold them yet.</p>

<h2>Fund Watchlist</h2>
<p>Add any mutual fund you're researching to track its NAV and performance over time before you decide to invest.</p>

<h2>Stock Watchlist</h2>
<p>Add stocks you're following to track their price movement alongside your actual holdings.</p>

<h2>Alerts</h2>
<div class="doc-callout">
  <i class="bi bi-bell doc-callout-icon"></i>
  <p>Watchlist items are checked periodically, so you can set alert conditions and get notified when something you're watching moves — no need to check back manually.</p>
</div>

<p>Both watchlists work well alongside the <a href="documentation.php?page=mutual-fund-research">Mutual Fund Research</a> and <a href="documentation.php?page=stock-research">Stock Research</a> sections — research first, then watch, then decide.</p>
