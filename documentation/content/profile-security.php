<p>Your Profile page is where you manage your personal details and account security.</p>

<h2>What you can update</h2>
<ul>
  <li>Name, phone number, and other personal details</li>
  <li>Your password</li>
  <li>Notification preferences, where available</li>
</ul>

<h2>Staying signed in</h2>
<p>Choosing "keep me logged in" at sign-in extends your session so you don't have to log in every visit on a trusted device. Avoid this option on a shared or public computer.</p>

<div class="doc-callout">
  <i class="bi bi-shield-lock doc-callout-icon"></i>
  <p>If you signed up with Google, your password is managed by your Google account — use Google's own security settings to change it.</p>
</div>
