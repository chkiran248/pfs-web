<p>You need an account to access the client portal, save your portfolio, and use PrimoAI. Creating one takes under a minute.</p>

<h2>Sign up with email</h2>
<div class="doc-steps">
  <div class="doc-step">
    <h3><span class="doc-step-num">1</span> Go to Register</h3>
    <p>Open <a href="auth/register.php">Create Account</a> from the homepage or click "Client Login → Register" on the login page.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">2</span> Enter your details</h3>
    <p>Provide your name, email address, phone number, and a password.</p>
  </div>
  <div class="doc-step">
    <h3><span class="doc-step-num">3</span> Verify your email</h3>
    <p>We'll send a one-time code (OTP) to your email. Enter it on the verification screen to activate your account. The code expires after a short window, so check your inbox (and spam folder) promptly.</p>
  </div>
</div>

<h2>Sign up with Google</h2>
<p>You can also create an account instantly using <strong>Sign in with Google</strong> on the <a href="auth/login.php">login page</a>. This skips the email verification step since Google has already confirmed your email address. Your account defaults to the standard client role, and you can start using the portal right away.</p>

<h2>Forgot your password?</h2>
<p>Use the <strong>Forgot Password</strong> link on the login page. We'll email you a secure reset link — it's valid for a limited time, so use it soon after you receive it.</p>

