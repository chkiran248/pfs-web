<p>Prime Financials has three plans. You can start free and upgrade whenever a feature you need requires it.</p>

<h2>Free</h2>
<p>Includes the core planning tools: SIP calculator, goal planner, tax calculator, NPS projector, insurance checker, risk assessment quiz, stock research, sector tracker, mutual fund advisory view, and basic portfolio tracking.</p>

<h2>Active Investor</h2>
<p>Everything in Free, plus the deeper portfolio tools — rebalancing suggestions, full document auto-import via PrimoAI, and more.</p>

<h2>Premium</h2>
<p>The full platform, including the most advanced PrimoAI capabilities and priority support from your advisor.</p>

