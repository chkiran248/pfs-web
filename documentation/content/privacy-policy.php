<p>This page summarizes, in plain language, how Prime Financials handles your information on this platform.</p>

<h2>What we collect</h2>
<ul>
  <li>Account details you provide — name, email, phone number</li>
  <li>Financial information you choose to add — portfolio holdings, goals, and documents you upload (such as a CAS or NSDL/CDSL statement)</li>
  <li>Basic usage information needed to keep your session secure and the platform running</li>
</ul>

<h2>How it's used</h2>
<p>Your data is used to power the features you use directly — your portfolio view, PrimoAI's answers, and your advisor's ability to assist you. It is not sold to third parties.</p>

<h2>Documents you upload</h2>
<p>Statements you upload (like a CAS or demat statement) are used only to extract your holdings into your portfolio. Passwords entered to unlock a protected PDF are used once, at upload time, and are not stored.</p>

<h2>Questions about your data</h2>
<p>For any question about what data we hold or how it's used, contact <strong>support@primefin.in</strong>.</p>

